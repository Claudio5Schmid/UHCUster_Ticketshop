-- Every function below is SECURITY DEFINER and re-checks is_admin() itself (belt and
-- braces on top of `grant execute ... to authenticated`), and writes its mutation plus
-- the matching audit_log row atomically in one transaction.
--
-- These are meant to be called through the admin's own authenticated Supabase session
-- (not a shared service-role connection): auth.uid() is how "who did this" gets
-- attributed, and that only resolves correctly when the caller has a real user JWT.
-- Carried forward to Phase 4/5/6 as a constraint on how their Server Actions connect.

-- Transition an order's status (neu / rechnung_versendet / bezahlt / storniert).
create or replace function public.transition_order_status(p_order_id uuid, p_new_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old_status text;
begin
  if not public.is_admin() then
    raise exception 'only admins can transition order status';
  end if;

  if p_new_status not in ('neu', 'rechnung_versendet', 'bezahlt', 'storniert') then
    raise exception 'invalid order status %', p_new_status;
  end if;

  select status into v_old_status from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'order % not found', p_order_id;
  end if;

  update public.orders set status = p_new_status where id = p_order_id;

  insert into public.audit_log (entity_type, entity_id, action, field_name, old_value, new_value, actor_type, actor_admin_id)
  values ('order', p_order_id, 'status_change', 'status', v_old_status, p_new_status, 'admin', auth.uid());
end;
$$;

grant execute on function public.transition_order_status(uuid, text) to authenticated;

